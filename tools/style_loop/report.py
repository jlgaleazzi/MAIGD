"""Markdown report of a style-loop run: what broke which GDD rule, what fixed it, what is left."""
import datetime
import difflib
from collections import Counter


def _counts(vs) -> str:
    c = Counter(v.rule for v in vs if v.rule != "JUDGE")
    return ", ".join(f"{k} x{n}" for k, n in sorted(c.items())) or "none"


def _text_diff(res) -> str:
    a, b = res.original, res.final
    if a.kind == "text":
        lines = []
        for f in ("title", "briefing"):
            if getattr(a, f) != getattr(b, f):
                lines += [f"- {f} before: {getattr(a, f)}", f"- {f} after:  {getattr(b, f)}"]
        return "\n".join(lines)
    diff = list(difflib.unified_diff(a.text.splitlines(), b.text.splitlines(), "before", "after", n=0, lineterm=""))
    if len(diff) > 40:
        diff = diff[:40] + [f"... ({len(diff) - 40} more diff lines)"]
    return "```diff\n" + "\n".join(diff) + "\n```" if diff else ""


def render(results, guide, args, written) -> str:
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    backend = args.backend if args.backend == "none" else f"{args.backend} {args.model or ''}".strip()
    out = [f"# Style loop report ({now})", "",
           f"Command: `{args.command}{' ' + args.what if args.what else ''}{' --fix' if args.fix else ''}`, "
           f"backend: {backend}, rules from `{guide.source}` "
           f"({len(guide.rules)} rules, {len(guide.palette)} colours, {sum(len(b) for _, b in guide.vocab)} banned terms).",
           "", "| Artifact | Status | Violations at start | Left | Rounds |", "|---|---|---|---|---|"]
    for r in results:
        rounds = max([s.iteration for s in r.steps], default=0)
        out.append(f"| {r.label} | {r.status} | {_counts(r.first_violations)} | {_counts(r.violations)} | {rounds} |")
    out += ["", f"Files written: {', '.join(f'`{p}`' for p in written) or 'none'}", ""]
    for r in results:
        if not (r.first_violations or r.steps or r.violations):
            continue
        out += [f"## {r.label}: {r.status}", ""]
        if getattr(r.final, "generated_by", None) and r.status == "report_only":
            out.append(f"Generated by `{r.final.generated_by}`: fix the generator, not the SVG.\n")
        if r.first_violations:
            out.append("Found:")
            out += [f"- {v.line()}" for v in r.first_violations]
            out.append("")
        if r.steps:
            out += ["| Round | Action | Before | After | Kept | Note |", "|---|---|---|---|---|---|"]
            for s in r.steps:
                note = s.note.replace("|", "/")[:300]
                out.append(f"| {s.iteration} | {s.action} | {s.violations_before} | {s.violations_after} | "
                           f"{'yes' if s.kept else 'no'} | {note} |")
            out.append("")
        if r.violations:
            out.append("Still breaking the Style Guide:")
            out += [f"- {v.line()}" for v in r.violations]
            out.append("")
        if r.changed:
            d = _text_diff(r)
            if d:
                out += ["Change:", "", d, ""]
    return "\n".join(out) + "\n"
